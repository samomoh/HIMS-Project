// Pure formatters for laboratory documents.
// Shared by the /api/laboratory/download route (and anywhere else a lab doc is rendered),
// so the on-screen preview and the downloaded file can never drift apart.

export interface LabDocPatient {
  id: number;
  firstName: string;
  lastName: string;
  dob: string | Date;
  gender: string;
  bloodGroup?: string | null;
  contact?: string | null;
}

export interface LabDocDoctor { id: number; name: string }

export interface LabDoc {
  id: number;
  testName: string;
  result: string | null;
  status: string;
  priority?: string | null;
  dateRequested: string | Date;
  dateCompleted?: string | Date | null;
  validatedBy?: string | null;
  patient: LabDocPatient;
  doctor: LabDocDoctor;
}

const fmtDate = (d?: string | Date | null) =>
  d ? new Date(d).toLocaleDateString() : 'N/A';
const fmtDateTime = (d?: string | Date | null) =>
  d ? new Date(d).toLocaleString() : 'N/A';

/** Reduce any string to a filename-safe ASCII slug. */
export const safeName = (s: string) =>
  (s || 'record').replace(/[^a-zA-Z0-9._-]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 40) || 'record';

const rule = (ch: string, n = 56) => ch.repeat(n);

export function formatLabRequest(lab: LabDoc): string {
  const p = lab.patient;
  return [
    'HEALTHAI HMIS  ·  LABORATORY REQUEST FORM',
    rule('═'),
    `Request No.   : LAB-${String(lab.id).padStart(5, '0')}`,
    `Priority      : ${(lab.priority || 'Routine').toUpperCase()}`,
    `Status        : ${lab.status}`,
    `Date Requested: ${fmtDateTime(lab.dateRequested)}`,
    rule('─'),
    'PATIENT',
    `  Name        : ${p.firstName} ${p.lastName}  (ID ${p.id})`,
    `  DOB / Gender: ${fmtDate(p.dob)} / ${p.gender}`,
    p.bloodGroup ? `  Blood Group : ${p.bloodGroup}` : null,
    p.contact ? `  Contact     : ${p.contact}` : null,
    rule('─'),
    'REQUESTING CLINICIAN',
    `  ${lab.doctor.name}`,
    rule('─'),
    'TEST / INVESTIGATION REQUESTED',
    `  • ${lab.testName}`,
    rule('─'),
    'SPECIMEN / INSTRUCTIONS',
    '  Collect per standard protocol; label with patient ID and request no.',
    '  For STAT/Urgent requests phone the lab on receipt.',
    rule('─'),
    '  [ ] Specimen received     Date/Time: __________   Tech: __________',
    '',
    'Generated by HealthAI HMIS — this form accompanies the specimen.',
    '',
  ].filter((l): l is string => l !== null).join('\n');
}

export function formatLabReport(lab: LabDoc): string {
  const p = lab.patient;
  return [
    'HEALTHAI HMIS  ·  LABORATORY RESULT REPORT',
    rule('═'),
    `Report No.    : LAB-${String(lab.id).padStart(5, '0')}-R`,
    `Test          : ${lab.testName}`,
    `Priority      : ${(lab.priority || 'Routine').toUpperCase()}`,
    `Requested     : ${fmtDateTime(lab.dateRequested)}`,
    `Completed     : ${fmtDateTime(lab.dateCompleted ?? null)}`,
    rule('─'),
    'PATIENT',
    `  Name        : ${p.firstName} ${p.lastName}  (ID ${p.id})`,
    `  DOB / Gender: ${fmtDate(p.dob)} / ${p.gender}`,
    p.bloodGroup ? `  Blood Group : ${p.bloodGroup}` : null,
    rule('─'),
    'REQUESTING CLINICIAN',
    `  ${lab.doctor.name}`,
    rule('─'),
    'RESULT',
    '',
    lab.result ? lab.result : '  (no result recorded)',
    '',
    rule('─'),
    'VALIDATION',
    `  Validated by : ${lab.validatedBy || '— pending validation —'}`,
    `  Released at  : ${fmtDateTime(lab.dateCompleted ?? null)}`,
    rule('─'),
    '  This report is electronically validated within HealthAI HMIS.',
    '',
  ].filter((l): l is string => l !== null).join('\n');
}

export const labDocFilename = (kind: 'request' | 'report', lab: LabDoc) =>
  kind === 'request'
    ? `LabRequest_${lab.id}_${safeName(lab.patient.lastName)}.txt`
    : `LabReport_${lab.id}_${safeName(lab.patient.lastName)}.txt`;
